export function guestLang() {
  return store('hotelops.lang.guest');
}

export function setGuestLang(l) {
  store('hotelops.lang.guest', l);
}

export function gt(key) {
  const l = guestLang() || 'en';
  return dict[l]?.[key] ?? dict.en[key] ?? key;
}

// Libellé d'un type de demande dans la langue du staff (fr/en).
export function kindLabel(kind, lang) {
  return (dict[lang] || dict.en)[kind === 'other' ? 'other' : kind] || kind;
}
